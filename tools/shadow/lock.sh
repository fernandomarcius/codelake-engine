#!/usr/bin/env bash
# Regenerates tools/shadow/requirements.txt: resolves requirements.in in the
# harness base image, pins every installed distribution, and lists the
# SHA-256 of every file PyPI publishes for that version (any platform), as
# pip-tools does, so `pip install --require-hashes` works on amd64 and arm64.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="$(sed -n 's/^FROM \(python[^ ]*\).*/\1/p' "$DIR/Dockerfile" | head -1)"
docker run --rm -v "$DIR":/shadow:ro "$BASE" sh -ec '
pip install --quiet --disable-pip-version-check --no-cache-dir -r /shadow/requirements.in >/dev/null
pip freeze --exclude pip --exclude setuptools --exclude wheel > /tmp/pins.txt
python - <<"PY"
import json, urllib.request
pins = sorted((l.strip() for l in open("/tmp/pins.txt") if "==" in l), key=str.lower)
print("# Generated by tools/shadow/lock.sh from requirements.in. Do not edit.")
for pin in pins:
    name, version = pin.split("==")
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as r:
        files = json.load(r)["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files})
    print(pin + "".join(f" \\\n    --hash=sha256:{h}" for h in hashes))
PY
' > "$DIR/requirements.txt"
echo "wrote $DIR/requirements.txt ($(grep -c '==' "$DIR/requirements.txt") pins)"
